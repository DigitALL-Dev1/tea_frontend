/** The version hash an approval is tied to. Click to copy the full SHA-256. */
export function HashChip({
  hash,
  className,
  label,
}: {
  hash: string | undefined;
  className?: string | undefined;
  label?: string;
}) {
  if (!hash) return <span className="text-xs text-muted-foreground">—</span>;
  return (
    <button
      type="button"
      onClick={() => {
        void navigator.clipboard?.writeText(hash).then(
          () => toast.success("Full SHA-256 copied"),
          () => undefined,
        );
      }}
      className={cn(
        "group inline-flex items-center gap-1 rounded border bg-muted/60 px-1.5 py-0.5 font-mono text-[11px] text-muted-foreground hover:bg-muted",
        className,
      )}
      title={`SHA-256 ${hash}`}
    >
      <Fingerprint className="size-3" aria-hidden />
      {label ? <span className="font-sans">{label}</span> : null}
      {shortHash(hash)}
      <Copy className="size-3 opacity-0 transition-opacity group-hover:opacity-100" aria-hidden />
    </button>
  );
}
