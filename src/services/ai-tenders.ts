/**
 * AI tenders API client: approved tenders moved into the AI processing queue.
 */

import { getStoredAuth } from "./auth";
import { API_BASE_URL } from "./api-config";

const API_BASE = `${API_BASE_URL}/api/v1/ai-tenders`;

export type AiStatus = "queued" | "processing" | "done" | "error";

export interface AiTender {
  id: number;
  approved_tender_id: number;
  tender_notice_id: string;
  title: string | null;
  agency: string | null;
  notice_type: string | null;
  reference: string | null;
  countries: string | null;
  deadline: string | null;
  url: string | null;
  status: AiStatus;
  ai_result: string | null;
  error: string | null;
  moved_by_username: string;
  moved_at: string | null;
  processed_at: string | null;
}

async function request<T>(init?: RequestInit, path = ""): Promise<T> {
  const auth = getStoredAuth();
  if (!auth) throw new Error("Not authenticated");

  const response = await fetch(`${API_BASE}${path}`, {
    ...init,
    headers: {
      ...(init?.body ? { "Content-Type": "application/json" } : {}),
      Authorization: `Bearer ${auth.token}`,
    },
  });
  if (!response.ok) {
    const error = await response.json().catch(() => ({ detail: "Request failed" }));
    throw new Error(error.detail || "Request failed");
  }
  return (await response.json()) as T;
}

/** Move an approved tender into the AI processing queue. */
export function moveToAi(approvedTenderId: number): Promise<AiTender> {
  return request<AiTender>({
    method: "POST",
    body: JSON.stringify({ approved_tender_id: approvedTenderId }),
  });
}

/** Tenders the current user moved to AI processing, newest first. */
export function getAiTenders(): Promise<AiTender[]> {
  return request<AiTender[]>();
}

export interface AiTenderDetail extends AiTender {
  proposal_html: string;
  /** template = starter outline, ai = generated by AI, user = edited and saved by the user */
  proposal_source: "template" | "ai" | "user";
  proposal_updated_at: string | null;
}

/** One AI tender with its proposal document. */
export function getAiTender(id: number): Promise<AiTenderDetail> {
  return request<AiTenderDetail>(undefined, `/${id}`);
}

/** Save the edited proposal. */
export function saveProposal(id: number, proposalHtml: string): Promise<AiTenderDetail> {
  return request<AiTenderDetail>(
    { method: "PUT", body: JSON.stringify({ proposal_html: proposalHtml }) },
    `/${id}/proposal`,
  );
}
